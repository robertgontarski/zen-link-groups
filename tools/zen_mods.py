#!/usr/bin/env python3
"""Adds this repository's mod to a Zen profile as a local Zen mod, or removes it.

    python3 -I tools/zen_mods.py install PROFILE [--style FILE] [--dry-run]
    python3 -I tools/zen_mods.py uninstall PROFILE [--dry-run]

It does on disk what Zen does when it installs a mod from its store:

- the mod's files go to <profile>/chrome/zen-themes/<id>/,
- the mod gets an entry in <profile>/zen-themes.json,
- <profile>/chrome/zen-themes.css, the sheet Zen loads at startup with the
  style of every enabled mod, is written again.

Zen writes that sheet itself only when a mod changes in its settings, so a
mod copied in while Zen is closed has to be added to it here. The format
follows Zen 1.24 (ZenMods.mjs). Zen overwrites the file on its next rebuild
with the same content.

The mod is described by theme.json at the top of the repository: its id,
name and other details, `preferences` (the settings file) and the style in
`style.chrome`. --style picks another file of the repository for Zen to load.

Uninstalling also removes the mod's settings (<id>.*) from prefs.js.

Standard library only. Zen must not have the profile open. The same file
serves Zen Link Size and Zen Link Groups.
"""

import argparse
import json
import os
import re
import shlex
import shutil
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENTRY_KEYS = (
    "id", "name", "description", "homepage", "readme", "image", "author",
    "version", "tags", "createdAt", "updatedAt",
)
HEADER = "/* Zen Mods - Generated by ZenMods."
HEADER_BODY = """* DO NOT EDIT THIS FILE DIRECTLY!
* Your changes will be overwritten.
* Instead, go to the preferences and edit the mods there.
*/
"""
FOOTER = "\n/* End of Zen Mods */\n"
DISABLE_ALL = re.compile(r'^user_pref\("zen\.themes\.disable-all",\s*true\);', re.M)


def file_mode():
    """The mode a newly created file gets (0644 with the usual umask)."""
    mask = os.umask(0)
    os.umask(mask)
    return 0o666 & ~mask


def mod_files(theme, style):
    """Files Zen keeps in a mod's folder, and where they come from in this repo."""
    return {"chrome.css": style, "preferences.json": theme["preferences"], "readme.md": "README.md"}


class Profile:
    def __init__(self, path, dry_run):
        self.path = path
        self.dry_run = dry_run
        self.mods_root = path / "chrome" / "zen-themes"
        self.mods_file = path / "zen-themes.json"
        self.sheet = path / "chrome" / "zen-themes.css"
        self.prefs = path / "prefs.js"

    def step(self, message):
        print(("  [dry-run] " if self.dry_run else "  ") + message)

    def foreign_files(self, mod_id):
        """Files this run would change that belong to another user, such as
        root after an install with sudo. Zen runs as you and cannot read them."""
        folder = self.mods_root / mod_id
        paths = [self.mods_root, folder, self.mods_file, self.sheet, self.prefs]
        if folder.is_dir():
            paths += folder.rglob("*")
        foreign = [p for p in paths if p.exists() and p.stat().st_uid != os.getuid()]
        # A folder in the list stands for everything in it (chown -R).
        return [p for p in foreign if not any(q in p.parents for q in foreign)]

    def read_mods(self):
        if not self.mods_file.exists():
            return {}
        try:
            mods = json.loads(self.mods_file.read_text(encoding="utf-8"))
        except json.JSONDecodeError as error:
            sys.exit(f"Error: {self.mods_file} is not valid JSON ({error}); fix or remove it first.")
        if not isinstance(mods, dict):
            sys.exit(f"Error: {self.mods_file} does not hold an object of mods.")
        return mods

    def write_text(self, path, text):
        if self.dry_run:
            return
        path.parent.mkdir(parents=True, exist_ok=True)
        # Written next to the target and renamed, so Zen never reads half a
        # file. A temporary file starts as 0600; give it a regular file's mode.
        with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=path.parent, delete=False) as tmp:
            tmp.write(text)
        os.chmod(tmp.name, file_mode())
        Path(tmp.name).replace(path)

    def write_mods(self, mods):
        self.write_text(self.mods_file, json.dumps(mods, indent=2, ensure_ascii=False) + "\n")

    def rebuild_sheet(self, mods, sources=None):
        """What ZenMods.mjs#writeStylesheet writes: every enabled mod's chrome.css.

        `sources` maps a mod id to the file its style comes from, for a mod
        whose folder a dry run did not create.
        """
        sources = sources or {}
        disabled = self.prefs.exists() and DISABLE_ALL.search(self.prefs.read_text(encoding="utf-8"))
        stamp = datetime.now(timezone.utc).strftime("%A, %B %d, %Y at %H:%M:%S UTC")
        parts = [f"{HEADER}\n* FILE GENERATED AT: {stamp}\n{HEADER_BODY}"]
        names = []
        for mod_id, mod in ({} if disabled else mods).items():
            if not isinstance(mod, dict) or mod.get("enabled") is False:
                continue
            style = sources.get(mod_id, self.mods_root / mod_id / "chrome.css")
            if not style.exists():
                continue
            names.append(mod.get("name", mod_id))
            parts.append(f"\n/* Name: {mod.get('name')} */\n")
            parts.append(f"/* Description: {mod.get('description')} */\n")
            parts.append(f"/* Author: @{mod.get('author')} */\n")
            if mod.get("readme"):
                parts.append(f"/* Readme: {mod['readme']} */\n")
            parts.append(style.read_text(encoding="utf-8"))
        parts.append(FOOTER)
        self.step(f"writing {self.sheet} ({', '.join(names) or 'no enabled mods'})")
        self.write_text(self.sheet, "".join(parts))


def raw_url(theme, name):
    """URL of a file in this repository, next to the README theme.json points at."""
    return theme["readme"].rsplit("/", 1)[0] + "/" + name


def install(profile, theme, style):
    mod_id = theme["id"]
    folder = profile.mods_root / mod_id
    files = mod_files(theme, style)
    profile.step(f"copying {', '.join(files)} to {folder}")
    if not profile.dry_run:
        folder.mkdir(parents=True, exist_ok=True)
        for target, source in files.items():
            shutil.copyfile(ROOT / source, folder / target)

    mods = profile.read_mods()
    previous = mods.get(mod_id) if isinstance(mods.get(mod_id), dict) else {}
    entry = {key: theme[key] for key in ENTRY_KEYS if key in theme}
    # Zen re-downloads a mod from these URLs if its folder goes missing.
    entry["style"] = raw_url(theme, style)
    entry["preferences"] = raw_url(theme, theme["preferences"])
    # A mod switched off in Zen's settings stays off after an update.
    entry["enabled"] = previous.get("enabled", True)
    mods[mod_id] = entry
    profile.step(f"registering {mod_id} {theme['version']} in {profile.mods_file}")
    profile.write_mods(mods)
    profile.rebuild_sheet(mods, {mod_id: ROOT / style})


def uninstall(profile, theme):
    mod_id = theme["id"]
    folder = profile.mods_root / mod_id
    if folder.exists():
        profile.step(f"removing {folder}")
        if not profile.dry_run:
            shutil.rmtree(folder)

    mods = profile.read_mods()
    if mod_id in mods:
        profile.step(f"removing {mod_id} from {profile.mods_file}")
        del mods[mod_id]
        profile.write_mods(mods)
    profile.rebuild_sheet(mods)

    if profile.prefs.exists():
        prefix = f'user_pref("{mod_id}.'
        lines = profile.prefs.read_text(encoding="utf-8").splitlines(keepends=True)
        kept = [line for line in lines if not line.startswith(prefix)]
        if len(kept) != len(lines):
            profile.step(f"removing {len(lines) - len(kept)} {mod_id}.* setting(s) from {profile.prefs}")
            profile.write_text(profile.prefs, "".join(kept))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("action", choices=("install", "uninstall"))
    parser.add_argument("profile", type=Path)
    parser.add_argument("--style", help="the repository's file Zen loads as the mod's style")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    if not (args.profile / "prefs.js").is_file():
        sys.exit(f"Error: {args.profile} does not look like a Zen profile (no prefs.js)")
    theme = json.loads((ROOT / "theme.json").read_text(encoding="utf-8"))
    style = args.style or theme["style"]["chrome"]
    if not (ROOT / style).is_file():
        sys.exit(f"Error: {ROOT / style} not found")
    profile = Profile(args.profile, args.dry_run)
    foreign = profile.foreign_files(theme["id"])
    if foreign:
        quoted = " ".join(shlex.quote(str(p)) for p in foreign)
        sys.exit(
            "Error: these files belong to another user (an earlier run with sudo?), so Zen,\n"
            "which runs as you, may not be able to read them:\n"
            + "".join(f"  {p}\n" for p in foreign)
            + "Make them yours, then run the installer again without sudo:\n"
            + f'  sudo chown -R "$(id -un)" {quoted}'
        )
    if args.action == "install":
        install(profile, theme, style)
    else:
        uninstall(profile, theme)
    return 0


if __name__ == "__main__":
    sys.exit(main())
